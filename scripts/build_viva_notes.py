"""docs/viva_notes.md: the viva questions and honest answers, as Markdown.

    python scripts/build_viva_notes.py

Reads only the result files, through scripts/doc_results.py (every number there carries its
`# from: <file>:<key path>` comment); the questions themselves are in scripts/viva_content.py, shared with the
viva guide PDF (scripts/build_viva_guide.py). Edit those, not the generated file.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from doc_results import ROOT  # noqa: E402
from viva_content import SECTIONS, SUBTITLE, TITLE  # noqa: E402

OUT = ROOT / "docs" / "viva_notes.md"


def card_md(num: str, c: dict) -> list[str]:
    out = [f"**Q {num}. {c['q']}**", "", c["a"], ""]
    if c.get("formula"):
        out += [f"> {c['formula']}", ""]
    if c.get("table"):
        head, rows = c["table"]
        out += ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
        out += ["| " + " | ".join(str(x) for x in r) + " |" for r in rows]
        out.append("")
    if c.get("points"):
        out += [f"- {p}" for p in c["points"]] + [""]
    for q, a in c.get("asks", []):
        out += [f"*If an examiner asks: {q}* {a}", ""]
    return out


def build() -> str:
    lines = ["<!-- Generated by scripts/build_viva_notes.py from the result files; edit the builder or "
             "scripts/viva_content.py, not this file. -->",
             f"# {TITLE}", "", SUBTITLE, ""]
    for i, (title, cards) in enumerate(SECTIONS, 1):
        lines += [f"## {i}. {title}", ""]
        for j, c in enumerate(cards, 1):
            lines += card_md(f"{i}.{j}", c)
    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    OUT.write_text(build(), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
