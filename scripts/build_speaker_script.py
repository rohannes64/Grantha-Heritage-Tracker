"""docs/Grantha_Speaker_Script.md: what each presenter says, slide by slide, for the 10-slide deck.

    python scripts/build_deck.py             # first: the script is read from the deck it writes
    python scripts/build_speaker_script.py

The words are the speaker notes of Grantha_Heritage_Tracker_SIH26096.pptx, which scripts/build_deck.py writes from
the result files (every number from reports/deliverable_facts.json or reports/features/*.json, every verdict chosen
by a branch on the facts). Reading them from the deck keeps one source: the script cannot drift from the slides.
`python scripts/check_claims.py` checks both files. To change what is said, edit the notes in scripts/build_deck.py.

Presenters: Rohan slides 1 to 4 (the problem, the app, the method), Rajith 5 to 7 (language, the map, the groups),
Sai Pranav 8 to 10 (DBSCAN, results and limits, summary). Change SPLIT to rebalance.
"""
from pathlib import Path

from pptx import Presentation

ROOT = Path(__file__).resolve().parents[1]
DECK = ROOT / "Grantha_Heritage_Tracker_SIH26096.pptx"
OUT = ROOT / "docs" / "Grantha_Speaker_Script.md"

ROHAN, RAJITH, SAI = "VEMURI ROHAN", "RAJITH SUNDAR", "ETIKALA SAI PRANAV"
SPLIT = [(4, ROHAN), (7, RAJITH), (10 ** 6, SAI)]            # (last slide, presenter), in order


def presenter(i: int) -> str:
    return next(who for last, who in SPLIT if i <= last)


def slides() -> list[tuple[str, str, str]]:
    """(presenter, slide title as on the deck, what to say), in slide order."""
    out = []
    for i, s in enumerate(Presentation(DECK).slides, 1):
        title = next((sh.text_frame.text for sh in s.shapes if sh.name == "Title"), None)
        if title is None:                                    # the title slide: its first line of text is the name
            title = next(sh.text_frame.text for sh in s.shapes if sh.has_text_frame and sh.text_frame.text.strip())
        notes = s.notes_slide.notes_text_frame.text.strip()
        paras = [p.strip() for p in notes.replace("\v", "\n").split("\n") if p.strip()]
        out.append((presenter(i), " ".join(title.split()), "\n\n".join(paras)))
    return out


def build() -> str:
    out = ["# Speaker script: Grantha Heritage Tracker (SIH26096)", "",
           "Generated by `scripts/build_speaker_script.py` from the speaker notes of "
           "`Grantha_Heritage_Tracker_SIH26096.pptx`, slide by slide. Edit the notes in `scripts/build_deck.py`, "
           "not this file.", ""]
    for i, (who, title, text) in enumerate(slides(), 1):
        out += [f"## Slide {i}: {title}", "", f"[{who} - SLIDE {i}]", "", text, ""]
    return "\n".join(out).rstrip() + "\n"


def main() -> None:
    OUT.write_text(build(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
