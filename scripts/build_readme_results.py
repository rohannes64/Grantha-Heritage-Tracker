"""Rewrite only the results block of README.md, between the RESULTS markers; the rest of the README is untouched.

    python scripts/build_readme_results.py

Every number comes from the result files through scripts/doc_results.py, where each one carries its
`# from: <file>:<key path>` comment. On the first run the older `results:start` / `results:end` markers are
replaced by the markers below.
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from doc_results import R, ROOT, f2, f3, met, n, pct, pct_ci, pts, pts_ci, num_ci  # noqa: E402

README = ROOT / "README.md"
START = "<!-- BEGIN RESULTS: generated by scripts/build_readme_results.py from the result files; do not edit by hand -->"
END = "<!-- END RESULTS -->"
BLOCK = re.compile(r"(?:<!-- BEGIN RESULTS:[^>]*-->|<!-- results:start[^>]*-->)\n.*?(?:<!-- END RESULTS -->|<!-- results:end -->)",
                   re.S)


def block() -> str:
    lines = [
        f"**Data** ({R.encoder}, whole-book text): {n(R.harvested)} books harvested in {R.languages} languages, "
        f"{n(R.usable)} usable ({pct(R.usable_share)}), split {n(R.train)} / {n(R.val)} / {n(R.test)} train / validation "
        f"/ test by a hash of each identifier. The archive's own OCR text is used for {n(R.text_archive)} books, our "
        f"Tesseract pages for {n(R.text_tesseract)}.",

        f"**Model**, chosen on train books: {R.linkage} linkage, {R.metric}, k = {R.k} "
        f"({'selection rule met' if R.rule_met else 'selection rule not met; pre-registered fallback used'}); "
        f"silhouette {f3(R.sil_train)}, script NMI {f3(R.nmi_train)}. Removing each language's average vector drops "
        f"script NMI from {f3(R.ce_nmi_before)} to {f3(R.ce_nmi_after)} on train books. DBSCAN (eps {f3(R.db_eps)}, "
        f"MinPts {R.db_minpts}) finds {R.db_clusters} clusters and calls {pct(R.db_noise)} of books noise.",

        f"**Targets on held-out test books** (fixed in advance, measured once): {R.n_met} of 3 met.",
        f"- T2 subject accuracy: {pct(R.t2_acc)} (95% CI {pct_ci(R.t2_acc_ci)}) on {R.t2_test_labels} labelled books, "
        f"against {pct(R.t2_script)} for guessing from the script and {pct(R.t2_common)} for the most common subject: "
        f"{pts(R.t2_points)} points over the best simple guess (95% CI {pts_ci(R.t2_points_ci)}, p = {R.t2_p:.4f}); "
        f"target +{R.target_t2:.0f}, **{met(R.met_t2)}**. On validation books the gain was {pts(R.t2_val_points)} "
        f"(95% CI {pts_ci(R.t2_val_points_ci)}).",
        f"- T1 page agreement: {pct(R.t1)} of single pages land in their book's group (95% CI {pct_ci(R.t1_ci)}), "
        f"against {pct(R.t1_chance)} by chance; target {pct(R.target_t1, 0)}, **{met(R.met_t1)}**.",
        f"- T3 stability: median bootstrap ARI {f2(R.t3)} on train books ({f2(R.boot_all)} on all usable books); "
        f"target {f2(R.target_t3)}, **{met(R.met_t3)}**.",

        f"**Against librarians' classes** (exploratory, {n(R.cat_labels)} test books): the groups are right "
        f"{pct(R.cat_acc)} of the time against {pct(R.cat_script)} for guessing from the script, {pts(R.cat_points)} "
        f"points (95% CI {pts_ci(R.cat_points_ci)}). The {R.k} groups do not separate the catalogue's main classes.",

        "**Archivist tools** (held-out evaluations in `reports/features/`):",
        f"- Class suggestion: the top suggestion is right {pct(R.sug_top1)} of the time (95% CI {pct_ci(R.sug_top1_ci)}) "
        f"against {pct(R.sug_base)} for the most common class; the right class is in the top three {pct(R.sug_top3)} "
        f"of the time ({n(R.sug_heldout)} books).",
        f"- Related books: {pct(R.rel_centred)} of a book's {R.rel_k} nearest neighbours are in another script after "
        f"centring, against {pct(R.rel_uncentred)} before.",
        f"- Edition finder: precision {f2(R.ed_precision)}, recall {pct(R.ed_recall)} (95% CI {pct_ci(R.ed_recall_ci)}), "
        f"from only {R.ed_groups} held-out edition groups, so the recall is very uncertain.",
        f"- Scan triage: AUC {f3(R.tri_auc)} (95% CI {num_ci(R.tri_auc_ci)}) on {R.tri_books} books, no better than "
        "chance at predicting where our OCR disagrees with the archive's.",
    ]
    out, prev_bullet = [], False
    for line in lines:                      # bullets stay together; paragraphs get a blank line between them
        bullet = line.startswith("- ")
        if out and not (bullet and prev_bullet):
            out.append("")
        out.append(line)
        prev_bullet = bullet or line.endswith(":") or line.endswith("met.")
    return "\n".join(out)


def main() -> None:
    s = README.read_text(encoding="utf-8")
    if not BLOCK.search(s):
        sys.exit("README.md has no results markers; add the BEGIN RESULTS / END RESULTS lines first")
    s = BLOCK.sub(lambda m: f"{START}\n{block()}\n{END}", s, count=1)
    README.write_text(s, encoding="utf-8")
    print(f"wrote the results block of {README}")


if __name__ == "__main__":
    main()
